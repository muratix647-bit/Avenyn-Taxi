begin;
do $test$
declare u uuid:=gen_random_uuid();u2 uuid:=gen_random_uuid();d uuid;d2 uuid;b uuid;r bookings;admin_id uuid;pool jsonb;denied boolean;at_time timestamp:=(now() at time zone 'Europe/Stockholm');
begin
 select auth_user_id into admin_id from dispatch_admins where active limit 1;
 if admin_id is null then raise exception 'TEST needs dispatch admin'; end if;
 insert into auth.users(id) values(u),(u2);
 insert into drivers(auth_user_id,full_name,approved,is_online,availability_status) values(u,'ROLLBACK nearest',true,true,'available') returning id into d;
 insert into drivers(auth_user_id,full_name,approved,is_online,availability_status) values(u2,'ROLLBACK next',true,true,'available') returning id into d2;
 insert into vehicles(name,driver_id) values('ROLLBACK car',d),('ROLLBACK next car',d2);
 insert into driver_locations(driver_id,latitude,longitude,updated_at) values(d,42,-30,now()),(d2,42.01,-30,now());
 insert into bookings(customer_name,pickup_address,booking_date,pickup_time,status,booking_number,pickup_point,price_breakdown) overriding system value values('ROLLBACK TEST','TEST pickup',(at_time+interval '1 day')::date,at_time::time,'scheduled',-900031,extensions.st_setsrid(extensions.st_makepoint(-30,42),4326)::extensions.geography,'{"dispatch_mode":"prebooking"}') returning id into b;
 perform set_config('request.jwt.claim.sub',admin_id::text,true);
 r:=dispatch_auto_assign(b,'dispatch_manual_auto');
 if r.driver_id is distinct from d or r.status<>'offered' then raise exception 'TEST FAIL manual auto prebooking'; end if;
 r:=dispatch_set_booking_status(b,'en_route');
 r:=dispatch_assign_driver(b,d2);
 if r.driver_id is distinct from d2 or r.status<>'assigned' then raise exception 'TEST FAIL reassign en route'; end if;
 if exists(select 1 from booking_driver_offers where booking_id=b and status='offered') then raise exception 'TEST FAIL stale offers'; end if;
 r:=dispatch_set_booking_status(b,'en_route');
 r:=dispatch_release_to_all(b);
 if r.driver_id is not null or r.status<>'new' or r.price_breakdown->>'dispatch_pool'<>'all' then raise exception 'TEST FAIL auction en route'; end if;
 perform set_config('request.jwt.claim.sub',u::text,true);
 pool:=driver_prebooking_pool();
 if not exists(select 1 from jsonb_array_elements(pool) x where x->>'id'=b::text and x->'price_breakdown'->>'broadcast_reopened_at' is not null) then raise exception 'TEST FAIL reopened visibility';end if;
 denied:=false;
 begin perform dispatch_release_to_all(b); exception when others then denied:=true; end;
 if not denied then raise exception 'TEST FAIL driver admin access';end if;
 r:=driver_claim_prebooking(b);
 perform set_config('request.jwt.claim.sub',u2::text,true);
 denied:=false;
 begin perform driver_claim_prebooking(b); exception when others then denied:=true; end;
 if not denied then raise exception 'TEST FAIL double acceptance';end if;
 perform set_config('request.jwt.claim.sub',admin_id::text,true);
 r:=dispatch_set_booking_status(b,'completed');
 r:=dispatch_set_booking_status(b,'en_route');
 if r.completed_at is not null or r.status<>'en_route' then raise exception 'TEST FAIL status correction';end if;
end $test$;
rollback;
